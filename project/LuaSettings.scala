import sbt._
import sbt.Keys._

/** Settings of the projects compiled to Lua (to run with LÖVE) by `lua-linker`, which links their
  * Scala.js IR to a Lua program instead of JavaScript.
  */
object LuaSettings {

  /** Like Scala.js' fastLink (`Dev`) and fullLink (`Prod`): the program's
    * `scala.scalajs.LinkingInfo.productionMode`.
    */
  sealed abstract class LuaMode(val name: String)
  object LuaMode {
    case object Dev  extends LuaMode("dev")
    case object Prod extends LuaMode("prod")
  }

  lazy val luaOutput = settingKey[File]("Directory where the Lua program is written")
  lazy val luaMode   = settingKey[LuaMode]("The mode the program is linked in (dev or prod)")
  lazy val luaConfig = settingKey[Map[String, String]](
    "The values of the generated Lua module bff_config (require(\"bff_config\"))"
  )
  lazy val luaLink = taskKey[File]("Link the program to Lua (main.lua), with its Lua modules")
  lazy val luaRun  = taskKey[Unit]("Link the program to Lua and run it with LÖVE")
  lazy val luaPackage =
    taskKey[Seq[File]]("Package the game with LÖVE for Windows, macOS and Linux (in target/dist)")
  lazy val luaPackageTitle =
    settingKey[String]("The packaged game's name (in camel case, the packages' file names)")
  lazy val luaProbe =
    taskKey[Unit]("Print statistics about the linked IR (set DUMP_CLASS=a.B,c.D to dump classes)")

  /** The module that `luaConfig` is written to, next to main.lua. */
  val configModule = "bff_config"

  /** @param linker
    *   the `lua-linker` project
    */
  def apply(linker: Project): Seq[Def.Setting[_]] = Seq(
    luaOutput := target.value / "lua",
    luaMode   := LuaMode.Dev,
    luaConfig := Map.empty,
    luaLink   := link(linker, luaMode, luaConfig, luaOutput).value,
    // the packages are what the players get: linked in prod mode, apart from luaLink's program
    luaPackage / luaMode   := LuaMode.Prod,
    luaPackage / luaOutput := target.value / "lua-package",
    luaProbe := Def.taskDyn {
      val mainCls = (Compile / mainClass).value.getOrElse(sys.error("No main class"))
      (linker / Compile / runMain).toTask(s" scalalove.linker.Probe $mainCls ${classpath.value}")
    }.value,
    luaRun := {
      val dir  = luaLink.value
      val love = loveCommand((LocalRootProject / target).value, streams.value.log)
      scala.sys.process.Process(Seq(love, dir.getAbsolutePath), None, "APPIMAGE_EXTRACT_AND_RUN" -> "1").!
    },
    luaPackageTitle := name.value,
    // LÖVE's builds are downloaded once, in the root's target directory
    luaPackage := LovePackage(
      link(linker, luaPackage / luaMode, luaPackage / luaConfig, luaPackage / luaOutput).value,
      luaPackageTitle.value,
      (LocalRootProject / target).value / s"love-${LovePackage.loveVersion}",
      target.value / "dist",
      streams.value.log
    )
  )

  /** What runs LÖVE (12): `LOVE` if set, on Linux x64 LÖVE's AppImage (downloaded once, see
    * [[LovePackage]]), otherwise the `love` command.
    */
  def loveCommand(rootTarget: File, log: Logger): String =
    sys.env.get("LOVE").filter(_.nonEmpty).getOrElse {
      val linuxX64 = System.getProperty("os.name") == "Linux" && System.getProperty("os.arch") == "amd64"
      if (linuxX64) LovePackage.appImage(rootTarget / s"love-${LovePackage.loveVersion}", log).getAbsolutePath
      else "love"
    }

  /** Links the program in `mode` to `output`, with the project's Lua modules (src/main/lua) and the
    * generated `configModule`.
    */
  private def link(
      linker: Project,
      mode: SettingKey[LuaMode],
      config: SettingKey[Map[String, String]],
      output: SettingKey[File]
  ): Def.Initialize[Task[File]] = Def.taskDyn {
    val cp      = classpath.value
    val out     = output.value
    val m       = mode.value
    val values  = config.value
    val mainCls = (Compile / mainClass).value.getOrElse(sys.error("No main class"))
    Def.task {
      (linker / Compile / runMain)
        .toTask(s" scalalove.linker.Main --mode ${m.name} $mainCls ${out.getAbsolutePath} $cp")
        .value
      // Lua modules of the project (src/main/lua) are copied next to main.lua
      val luaSources = (Compile / sourceDirectory).value / "lua"
      if (luaSources.exists()) IO.copyDirectory(luaSources, out, overwrite = true)
      IO.write(out / s"$configModule.lua", configLua(values))
      out
    }
  }

  /** A Lua module returning the table of `values`. */
  private def configLua(values: Map[String, String]): String = {
    val entries = values.toSeq.sortBy(_._1).map { case (key, value) =>
      s"  [${luaString(key)}] = ${luaString(value)},\n"
    }
    s"-- Generated by luaLink (luaConfig in the build): do not edit\nreturn {\n${entries.mkString}}\n"
  }

  private def luaString(s: String): String =
    s.flatMap {
      case '\\' => "\\\\"
      case '"'  => "\\\""
      case '\n' => "\\n"
      case '\r' => "\\r"
      case c if c < ' ' => f"\\${c.toInt}%03d"
      case c => c.toString
    }.mkString("\"", "", "\"")

  private def classpath = Def.task {
    (Compile / fullClasspath).value.map(_.data.getAbsolutePath).mkString(java.io.File.pathSeparator)
  }
}
